export function isProtocolErrorCode(code: number): code is ProtocolErrorCode {
  return Object.prototype.hasOwnProperty.call(PROTOCOL_ERROR_CATALOG, code);
}

export function getProtocolErrorMetadata(code: ProtocolErrorCode | number): ProtocolErrorMetadata {
  if (isProtocolErrorCode(code)) {
    return PROTOCOL_ERROR_CATALOG[code];
  }
  return PROTOCOL_ERROR_CATALOG[ProtocolErrorCode.Unknown];
}
